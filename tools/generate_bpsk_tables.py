"""Generate the fixed-point LUT and quantize the existing matched filter."""
import math
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = (root / "components/nuepsk/include/pskcore_rx_tables.h").read_text()
fir = re.search(r"s_bit_fir\[65\] = \{(.*?)\};", source, re.S).group(1)
coeffs = [round(float(v.strip().rstrip("f")) * 32768) for v in fir.split(",") if v.strip()]
assert len(coeffs) == 65 and sum(abs(v) for v in coeffs) < 2 * 32768
sine = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)]
def table(name, values):
    lines = [", ".join(str(v) for v in values[i:i+12]) for i in range(0, len(values), 12)]
    return f"static const int16_t {name}[{len(values)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"
(root / "main/bpsk_tables.h").write_text(
    "// Generated by tools/generate_bpsk_tables.py; do not edit.\n#pragma once\n#include <stdint.h>\n\n"
    + table("bpsk_fir_q15", coeffs) + "\n"
    + table("bpsk_fir8_q15", [2 * v for v in coeffs[::2]]) + "\n"
    + table("bpsk_sine_q15", sine))

# 47-tap Hamming low-pass, 3.4 kHz cutoff, 16 kHz codec rate.
lpf = []
for n in range(47):
    x = n - 23
    sinc = 2 * 3400 / 16000 if not x else math.sin(2 * math.pi * 3400 / 16000 * x) / (math.pi * x)
    lpf.append(sinc * (0.54 - 0.46 * math.cos(2 * math.pi * n / 46)))
scale = sum(lpf)
lpf_q15 = [round(v / scale * 32768) for v in lpf]
assert sum(abs(v) for v in lpf_q15) * 16384 < 2**31
(root / "main/audio_filter.h").write_text(
    "// Generated by tools/generate_bpsk_tables.py; 16 kHz -> 8 kHz.\n#pragma once\n#include <stdint.h>\n"
    + table("audio_lpf_q15", lpf_q15))
